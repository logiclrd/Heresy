using System;

using Heresy.Core.Filters;

namespace Heresy.Render.Filters;

/// <summary>
/// Four-pole TPT ladder with an implicit saturating feedback/input junction.
/// The nonlinear feedback equation is solved at each oversampled instant;
/// the four one-pole sections remain linear. This is deliberately distinct
/// from the un-saturated linear ladder and from nonlinear-per-pole models.
/// </summary>
public sealed class SaturatedLadderFilterStageFactory : IStreamingFilterStageFactory
{
	public static SaturatedLadderFilterStageFactory Instance { get; } = new();

	public const int ParameterTransitionFrames = 32;
	public const double MaximumFeedback = LinearLadderFilterStageFactory.MaximumFeedback;
	public const int MaximumOversampling = 4;
	public const int MaximumRootIterations = 12;

	private SaturatedLadderFilterStageFactory() { }

	public IStreamingFilterStagePlan Prepare(PreparedFilterStage stage, int sampleRate)
	{
		ArgumentNullException.ThrowIfNull(stage);
		if (stage.Kind != FilterKind.LadderSaturated)
			throw new ArgumentException(
				"A saturated ladder factory requires a saturated ladder stage.",
				nameof(stage));
		if (sampleRate <= 0)
			throw new ArgumentOutOfRangeException(nameof(sampleRate));

		double cutoff = stage.Parameters["CutoffHz"].NumericValue;
		if (!double.IsFinite(cutoff) || cutoff <= 0 || cutoff >= sampleRate * 0.5)
			throw new ArgumentOutOfRangeException(nameof(stage),
				$"Saturated ladder cutoff {cutoff} Hz must lie strictly below "
				+ $"base-rate Nyquist ({sampleRate * 0.5} Hz).");
		double resonance = stage.Parameters["Resonance"].NumericValue;
		if (!double.IsFinite(resonance) || resonance < 0 || resonance > 1)
			throw new ArgumentOutOfRangeException(nameof(stage),
				"Saturated ladder resonance must lie in [0, 1].");
		double drive = stage.Parameters["Drive"].NumericValue;
		if (!double.IsFinite(drive) || drive < 0.1 || drive > 10)
			throw new ArgumentOutOfRangeException(nameof(stage),
				"Saturated ladder Drive must lie in [0.1, 10].");

		int factor = stage.Parameters["Oversampling"].ChoiceValue switch
		{
			"1x" => 1,
			"2x" => 2,
			"4x" => 4,
			_ => throw new ArgumentException(
				"Saturated ladder Oversampling must be 1x, 2x or 4x.",
				nameof(stage)),
		};
		// Avoid integer overflow and any need for unbounded oversampled
		// buffers: the processor works incrementally, in fixed-size state.
		if ((long)sampleRate * factor > int.MaxValue)
			throw new ArgumentOutOfRangeException(nameof(sampleRate),
				"Oversampled sample rate exceeds the supported range.");
		int internalRate = sampleRate * factor;
		double g = Math.Tan(Math.PI * cutoff / internalRate);
		double feedback = MaximumFeedback * resonance;
		if (!double.IsFinite(g) || !(g > 0) || !(feedback >= 0)
			|| !(feedback < 4))
			throw new ArgumentOutOfRangeException(nameof(stage),
				"Saturated ladder has invalid integration coefficients.");

		// Tanh has derivative between zero and one, so the maximum
		// small-signal open-loop feedback gain is the same as for the
		// stable linear ladder. The nonlinear junction only reduces it.
		double radius = MaximumDigitalPoleRadius(g, feedback);
		if (!double.IsFinite(radius) || !(radius >= 0) || !(radius < 1))
			throw new ArgumentOutOfRangeException(nameof(stage),
				"Saturated ladder small-signal poles are unstable.");

		// The four repeated poles at zero resonance require an n^3
		// decay allowance. Convert oversampled work to host PCM frames,
		// then include the four-stage reconstruction filter's decay.
		double decay = radius == 0 ? 0 : -Math.Log(radius);
		double baseFrames = radius == 0 ? 2 : Math.Log(1e20) / decay;
		double allowance = radius == 0 ? 0
			: 3 * Math.Log(1 + baseFrames) / decay;
		double internalFrames = Math.Ceiling(baseFrames + allowance) + 8;
		double outputFrames = internalFrames / factor;
		double reconstructionGain = 0;
		if (factor > 1)
		{
			// Four identical TPT poles at 0.42*base rate attenuate
			// aliases before decimation, including the image bands
			// generated by the nonlinear feedback junction.
			double reconstructionG = Math.Tan(
				Math.PI * (0.42 * sampleRate) / internalRate);
			reconstructionGain = reconstructionG / (1 + reconstructionG);
			double reconstructionPole = Math.Abs(1 - 2 * reconstructionGain);
			if (!(reconstructionGain > 0 && reconstructionGain < 1))
				throw new ArgumentOutOfRangeException(nameof(stage),
					"Invalid reconstruction low-pass coefficients.");
			if (reconstructionPole > 0)
				outputFrames += (Math.Log(1e20)
					+ 3 * Math.Log(1 + baseFrames)) /
					(-Math.Log(reconstructionPole)) / factor;
		}
		double estimated = Math.Ceiling(outputFrames) + 8;
		int tailFrames = !double.IsFinite(estimated) || estimated >= int.MaxValue
			? int.MaxValue : Math.Max(8, (int)estimated);
		return new LadderPlan(g, feedback, drive, factor,
			reconstructionGain, tailFrames);
	}

	private static double MaximumDigitalPoleRadius(double g, double feedback)
	{
		double rootRadius = Math.Sqrt(Math.Sqrt(feedback));
		double maximum = 0;
		for (int i = 0; i < 4; i++)
		{
			double angle = (Math.PI + 2 * Math.PI * i) / 4;
			double real = -1 + rootRadius * Math.Cos(angle);
			double imaginary = rootRadius * Math.Sin(angle);
			double imaginaryG = g * imaginary;
			double numerator = Math.Sqrt(
				(1 + g * real) * (1 + g * real) + imaginaryG * imaginaryG);
			double denominator = Math.Sqrt(
				(1 - g * real) * (1 - g * real) + imaginaryG * imaginaryG);
			maximum = Math.Max(maximum, numerator / denominator);
		}
		return maximum;
	}

	private sealed class LadderPlan(
		double g, double feedback, double drive, int factor,
		double reconstructionGain, int tailFrames) : IStreamingFilterStagePlan
	{
		public double G { get; } = g;
		public double Feedback { get; } = feedback;
		public double Drive { get; } = drive;
		public int Factor { get; } = factor;
		public double ReconstructionGain { get; } = reconstructionGain;
		public int TailFrames { get; } = tailFrames;
		public IStreamingFilterStageState CreateState() => new LadderState(this);
	}

	private sealed class LadderState : IStreamingFilterStageState
	{
		private readonly double[] _integrators = new double[4];
		private readonly double[] _reconstruction = new double[4];
		private LadderPlan _plan;
		private double _g;
		private double _feedback;
		private double _drive;
		private double _startG;
		private double _startFeedback;
		private double _startDrive;
		private double _previousInput;
		private int _remaining;
		private double _gain;
		private double _bypass;
		private double _gainFourth;

		public LadderState(LadderPlan plan)
		{
			_plan = plan;
			_g = plan.G;
			_feedback = plan.Feedback;
			_drive = plan.Drive;
			_startG = _g;
			_startFeedback = _feedback;
			_startDrive = _drive;
			UpdateCoefficients();
		}

		private LadderState(LadderState other)
		{
			Array.Copy(other._integrators, _integrators, 4);
			Array.Copy(other._reconstruction, _reconstruction, 4);
			_plan = other._plan;
			_g = other._g;
			_feedback = other._feedback;
			_drive = other._drive;
			_startG = other._startG;
			_startFeedback = other._startFeedback;
			_startDrive = other._startDrive;
			_previousInput = other._previousInput;
			_remaining = other._remaining;
			_gain = other._gain;
			_bypass = other._bypass;
			_gainFourth = other._gainFourth;
		}

		private void UpdateCoefficients()
		{
			_gain = _g / (1 + _g);
			_bypass = 1 - _gain;
			double square = _gain * _gain;
			_gainFourth = square * square;
		}

		public float Process(float sample)
		{
			double current = float.IsFinite(sample) ? sample : 0;
			int factor = _plan.Factor;
			double result = 0;
			for (int substep = 1; substep <= factor; substep++)
			{
				if (_remaining > 0)
				{
					double progress = (double)(
						ParameterTransitionFrames * factor - _remaining + 1)
						/ (ParameterTransitionFrames * factor);
					_g = _startG + (_plan.G - _startG) * progress;
					_feedback = _startFeedback
						+ (_plan.Feedback - _startFeedback) * progress;
					_drive = _startDrive + (_plan.Drive - _startDrive) * progress;
					UpdateCoefficients();
					_remaining--;
				}
				// Piecewise-linear input reconstruction, with no frame
				// buffering and deterministic boundaries.
				double interpolated = _previousInput
					+ (current - _previousInput) * substep / factor;
				double output = ProcessInternal(interpolated);
				if (factor > 1)
				{
					double gain = _plan.ReconstructionGain;
					for (int stage = 0; stage < _reconstruction.Length; stage++)
					{
						double v = gain * (output - _reconstruction[stage]);
						double low = _reconstruction[stage] + v;
						_reconstruction[stage] = Flush(low + v);
						output = low;
					}
				}
				result = output;
			}
			_previousInput = current;
			if (!double.IsFinite(result) || Math.Abs(result) < 1e-20)
				return 0;
			return (float)Math.Clamp(result, -float.MaxValue, float.MaxValue);
		}

		private double ProcessInternal(double excitation)
		{
			double gain2 = _gain * _gain;
			double gain3 = gain2 * _gain;
			double memory = _bypass * (gain3 * _integrators[0]
				+ gain2 * _integrators[1]
				+ _gain * _integrators[2] + _integrators[3]);
			double bound = _gainFourth / _drive;
			double lower = memory - bound;
			double upper = memory + bound;
			// y4 = memory + G^4 * tanh(Drive * (x - K*y4))/Drive.
			// The left-hand side minus right-hand side is strictly
			// increasing (derivative >= 1): exactly one finite root.
			// Hybrid Newton/bisection keeps every iterate bracketed and
			// puts a fixed upper limit on nonlinear processing cost.
			double fourth = Math.Clamp(
				(_gainFourth * excitation + memory)
					/ (1 + _feedback * _gainFourth),
				lower, upper);
			for (int iteration = 0; iteration < MaximumRootIterations; iteration++)
			{
				double tanh = Math.Tanh(_drive * (excitation - _feedback * fourth));
				double residual = fourth - memory - _gainFourth * tanh / _drive;
				if (Math.Abs(residual) < 1e-14)
					break;
				if (residual > 0)
					upper = fourth;
				else
					lower = fourth;
				double derivative = 1 + _gainFourth * _feedback
					* (1 - tanh * tanh);
				double candidate = fourth - residual / derivative;
				fourth = double.IsFinite(candidate)
					&& candidate > lower && candidate < upper
						? candidate : (lower + upper) * 0.5;
			}

			double input = Math.Tanh(
				_drive * (excitation - _feedback * fourth)) / _drive;
			for (int stage = 0; stage < _integrators.Length; stage++)
			{
				double output = _gain * input + _bypass * _integrators[stage];
				_integrators[stage] = Flush(2 * output - _integrators[stage]);
				input = output;
			}
			return input;
		}

		private static double Flush(double value)
			=> double.IsFinite(value) && Math.Abs(value) >= 1e-20
				? value : 0;

		public IStreamingFilterStageState Clone() => new LadderState(this);

		public void Reconfigure(IStreamingFilterStagePlan plan)
		{
			if (plan is not LadderPlan next || next.Factor != _plan.Factor)
				throw new ArgumentException(
					"Saturated ladder must retain its structural oversampling "
					+ "factor when updating existing histories.", nameof(plan));
			if (_g == next.G && _feedback == next.Feedback
				&& _drive == next.Drive)
			{
				_plan = next;
				_startG = _g;
				_startFeedback = _feedback;
				_startDrive = _drive;
				_remaining = 0;
				return;
			}
			// Keep integrators, reconstruction filter, and input phase.
			// A new edit during an unfinished transition starts from
			// its current interpolated values.
			_startG = _g;
			_startFeedback = _feedback;
			_startDrive = _drive;
			_plan = next;
			_remaining = ParameterTransitionFrames * next.Factor;
		}
	}
}
